-- ====================================================================
-- Happy Paws & Pixels – Supabase Database Schema
-- Run this in your Supabase Project: SQL Editor -> New Query -> Run
-- ====================================================================

-- 1. PETS TABLE
CREATE TABLE IF NOT EXISTS public.pets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_name TEXT NOT NULL,
    species TEXT NOT NULL DEFAULT 'Dog',
    breed TEXT,
    age TEXT,
    gender TEXT,
    owner_name TEXT NOT NULL,
    owner_phone TEXT NOT NULL,
    owner_email TEXT,
    emergency_contact TEXT,
    diet_notes TEXT,
    medical_notes TEXT,
    stay_start TEXT,
    stay_end TEXT,
    status TEXT DEFAULT 'Active',
    room_number TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. VOLUNTEERS TABLE
CREATE TABLE IF NOT EXISTS public.volunteers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    availability TEXT,
    activities TEXT,
    experience TEXT,
    motivation TEXT,
    status TEXT DEFAULT 'Pending',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. DIGITAL CONSENTS TABLE
CREATE TABLE IF NOT EXISTS public.consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_name TEXT NOT NULL,
    pet_name TEXT NOT NULL,
    owner_phone TEXT NOT NULL,
    owner_email TEXT,
    emergency_vet_consent BOOLEAN DEFAULT TRUE,
    terms_accepted BOOLEAN DEFAULT TRUE,
    signature_name TEXT NOT NULL,
    signature_date TEXT,
    status TEXT DEFAULT 'Signed',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. FEEDBACK TABLE
CREATE TABLE IF NOT EXISTS public.feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_name TEXT NOT NULL,
    pet_name TEXT NOT NULL,
    overall_rating INTEGER DEFAULT 5,
    cleanliness_rating INTEGER DEFAULT 5,
    staff_rating INTEGER DEFAULT 5,
    care_rating INTEGER DEFAULT 5,
    comments TEXT,
    recommend TEXT DEFAULT 'Yes',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. ENQUIRIES / CONTACT TABLE
CREATE TABLE IF NOT EXISTS public.enquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT,
    pet_type TEXT,
    message TEXT NOT NULL,
    status TEXT DEFAULT 'New',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Allow public insert and public read for demonstration/CEP app
-- ====================================================================

ALTER TABLE public.pets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.volunteers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.consents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.enquiries ENABLE ROW LEVEL SECURITY;

-- Allow public read & insert on pets
CREATE POLICY "Public read pets" ON public.pets FOR SELECT USING (true);
CREATE POLICY "Public insert pets" ON public.pets FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update pets" ON public.pets FOR UPDATE USING (true);
CREATE POLICY "Public delete pets" ON public.pets FOR DELETE USING (true);

